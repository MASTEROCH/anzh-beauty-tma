-- 001 · Схема и общие соглашения.
--
-- Все таблицы продукта живут в отдельной схеме PostgreSQL (контракт §5.1).
-- Перенос в общую базу — одна миграция вида
--   alter table anzh.bookings set schema public;
-- вместо ручной сверки таблица за таблицей.
--
-- Имя схемы намеренно зашито в SQL, а не вынесено в переменную: подстановка
-- имени схемы в каждый файл делает миграции невыполнимыми обычным psql, а
-- выигрыш даёт нулевой — переезд всё равно описывается отдельной миграцией.

create schema if not exists anzh;

-- updated_at обновляется базой, а не прикладным кодом: пропущенный вызов в
-- одном месте кода делает поле бесполезным во всей таблице.
create or replace function anzh.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;
